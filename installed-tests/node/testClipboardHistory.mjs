import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const source = await readFile(new URL('../../src/service/utils/clipboardHistory.js', import.meta.url), 'utf8');
const {default: History} = await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
const offer = id => ({id, origin: 'source', types: ['text/plain'], files: []});
let evicted = [];
const h = new History({maxItems: 2, maxBytes: 10000, onEvict: e => evicted.push(e.key)});
const bytes = new Uint8Array([65]);
h.addLocal(offer('a'), new Map([['text/plain', bytes]]));
bytes[0] = 66;
assert.equal(h.getLocalLease('a').values.get('text/plain')[0], 65);
h.addRemote(offer('a'), 'Peer');
assert.deepEqual(h.list().map(e => e.direction), ['remote', 'local']);
assert.equal(h.list()[0].peerName, 'Peer');
h.addLocal(offer('b'));
assert.equal(h.getLocalLease('a'), null);
assert.deepEqual(evicted, ['local:a']);
assert.equal(h.attachValue('a', 'text/plain', new Uint8Array([1, 2])), true);
assert.equal(h.attachValue('a', 'image/png', new Uint8Array(1)), false);
assert.equal(h.attachValue('missing', 'text/plain', new Uint8Array(1)), false);
const previous = h.bytes;
h.attachValue('a', 'text/plain', new Uint8Array([1]));
assert.equal(h.bytes, previous - 1);
let changes = 0;
const unsubscribe = h.subscribe(() => changes++);
h.setLimits({maxItems: 0, maxBytes: 0});
assert.equal(h.list().length, 0);
assert.equal(changes, 1);
unsubscribe();
h.clear();
assert.throws(() => h.setLimits({maxItems: -1}));
assert.throws(() => h.setLimits({maxItems: 2, maxBytes: Infinity}));
const files = new History({maxBytes: 500});
const f = {...offer('f'), files: [{name: 'large.bin', size: 1000}], types: ['text/uri-list']};
files.addRemote(f);
assert.equal(files.list().length, 1, 'metadata-only offers fit without fetching file data');
assert.equal(files.attachFiles('f', ['https://example.com']), false);
assert.equal(files.attachFiles('f', ['file:///private/cache']), false);
assert.equal(files.list().length, 1, 'oversized downloaded file keeps metadata-only lease');
assert.equal(files.list()[0].uris, null);
const local = new History();
local.addLocal(f);
f.files[0].name = 'changed';
assert.equal(local.getLocalLease('f').offer.files[0].name, 'large.bin');
local.clear();
assert.equal(local.bytes, 0);
console.log('Clipboard history tests passed');

const limited = new History({maxItems: 3, maxBytes: 500});
limited.addLocal(offer('keep'));
limited.addLocal(offer('big'), new Map([['text/plain', new Uint8Array(1000)]]));
assert.ok(limited.bytes <= 500);
const populated = new History();
populated.addRemote(offer('r'), 'remote');
const mutable = new Uint8Array([4]);
populated.attachValue('r', 'text/plain', mutable);
mutable[0] = 9;
assert.equal(populated.get('remote:r').values.get('text/plain')[0], 4);
assert.deepEqual(populated.get('remote:r').availableTypes, ['text/plain']);
populated.addLocal(offer('r'));
populated.remove('remote:r');
assert.ok(populated.getLocalLease('r'));
assert.equal(populated.get('remote:r'), null);
